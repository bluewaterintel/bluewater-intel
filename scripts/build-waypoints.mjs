#!/usr/bin/env node
/**
 * Build bw-waypoints.js (offline iOS fallback) from supabase-m1/seed/waypoints.ndjson.
 *
 * The live Supabase `waypoints` table is authoritative. After editing there,
 * snapshot to git with `npm run pull:waypoints`.
 *
 * Usage:
 *   npm run build:waypoints
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NDJSON = join(root, 'supabase-m1/seed/waypoints.ndjson');
const TYPES_PATH = join(root, 'supabase-m1/seed/waypoint_types.json');

function readNdjson(path) {
  return readFileSync(path, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((line) => JSON.parse(line));
}

function main() {
  const types = JSON.parse(readFileSync(TYPES_PATH, 'utf8'));
  const rows = readNdjson(NDJSON);
  for (const w of rows) {
    if (!w.name || !Number.isFinite(w.lat) || !Number.isFinite(w.lng) || !w.t) {
      throw new Error(`invalid waypoint row: ${JSON.stringify(w).slice(0, 120)}`);
    }
    if (!types[w.t]) throw new Error(`unknown type code "${w.t}" on "${w.name}"`);
  }

  const wp = rows.map((w) => [w.name, w.lat, w.lng, w.t]);
  const blob = { version: 6, types, count: rows.length, wp };
  const js = `/* Auto-generated by scripts/build-waypoints.mjs — do not edit manually */\nwindow.BW_WAYPOINTS=${JSON.stringify(blob)};\n`;
  writeFileSync(join(root, 'bw-waypoints.js'), js);

  const byType = {};
  for (const w of rows) byType[w.t] = (byType[w.t] || 0) + 1;
  console.log(`Read ${rows.length} waypoints from supabase-m1/seed/waypoints.ndjson`);
  console.log('Types:', byType);
  console.log(`Wrote bw-waypoints.js (${(js.length / 1024).toFixed(0)} KB)`);
}

main();
