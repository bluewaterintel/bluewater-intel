#!/usr/bin/env node
/**
 * Generate bw-config.js from environment variables or .env file
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, '.env');
const nativeDefaultsPath = join(root, 'ios-resources/native-client-config.json');

function loadNativeDefaults() {
  if (!existsSync(nativeDefaultsPath)) return {};
  try {
    const j = JSON.parse(readFileSync(nativeDefaultsPath, 'utf8'));
    return {
      SUPABASE_URL: j.supabaseUrl || '',
      SUPABASE_ANON_KEY: j.supabaseAnonKey || '',
      REVENUECAT_IOS_API_KEY: j.revenueCatIosApiKey || '',
      REVENUECAT_ANDROID_API_KEY: j.revenueCatAndroidApiKey || '',
    };
  } catch {
    return {};
  }
}

function loadEnv() {
  const env = { ...loadNativeDefaults(), ...process.env };
  if (existsSync(envPath)) {
    for (const line of readFileSync(envPath, 'utf8').split('\n')) {
      const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
      if (!m || line.trimStart().startsWith('#')) continue;
      env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
  }
  return env;
}

const native = process.argv.includes('--native');
const outIdx = process.argv.indexOf('--out');
const outPath = outIdx >= 0 ? process.argv[outIdx + 1] : null;
const env = loadEnv();

function readAndroidVersion() {
  const gradlePath = join(root, 'android/app/build.gradle');
  if (!existsSync(gradlePath)) return { code: 0, name: '' };
  const text = readFileSync(gradlePath, 'utf8');
  const codeM = text.match(/versionCode\s+(\d+)/);
  const nameM = text.match(/versionName\s+"([^"]+)"/);
  return {
    code: codeM ? Number(codeM[1]) : 0,
    name: nameM ? nameM[1] : '',
  };
}

function nativeWebBundleMeta() {
  const speciesPath = join(root, 'bw-data-species.js');
  const indexPath = join(root, 'index.html');
  if (!existsSync(speciesPath)) return null;
  const sp = readFileSync(speciesPath, 'utf8');
  let cacheTag = '';
  if (existsSync(indexPath)) {
    const m = readFileSync(indexPath, 'utf8').match(/bw-data-species\.js\?v=([^"]+)/);
    if (m) cacheTag = m[1];
  }
  return {
    speciesMenuCount: (sp.match(/\{id:"/g) || []).length,
    halibut: sp.includes('id:"halibut"'),
    whiteSeabass: sp.includes('id:"whiteseabass"'),
    cacheTag,
  };
}
const url = env.SUPABASE_URL || env.VITE_SUPABASE_URL || '';
const anon = env.SUPABASE_ANON_KEY || env.VITE_SUPABASE_ANON_KEY || '';
const rcIosKey = env.REVENUECAT_IOS_API_KEY || '';
const rcAndroidKey = env.REVENUECAT_ANDROID_API_KEY || '';

if (!url || !anon || url.includes('YOURPROJECT') || anon.includes('YOUR_ANON')) {
  console.warn('Warning: SUPABASE_URL or SUPABASE_ANON_KEY not set — bw-config.js will use placeholders.');
}

const webBundle = native ? nativeWebBundleMeta() : null;
const androidVer = native ? readAndroidVersion() : { code: 0, name: '' };
const out = `// Auto-generated by scripts/generate-bw-config.mjs — do not edit manually
window.BW_DATA_CONFIG = {
  supabaseUrl: ${JSON.stringify(url || 'https://YOURPROJECT.supabase.co')},
  supabaseAnonKey: ${JSON.stringify(anon || 'YOUR_ANON_KEY')},
  embeddedFallback: ${native},
  queryTimeoutMs: 8000,${native ? `
  revenueCatIosApiKey: ${JSON.stringify(rcIosKey || 'YOUR_REVENUECAT_IOS_KEY')},
  revenueCatAndroidApiKey: ${JSON.stringify(rcAndroidKey || 'YOUR_REVENUECAT_ANDROID_KEY')},
  nativeVersionCode: ${androidVer.code || 0},
  nativeVersionName: ${JSON.stringify(androidVer.name || '')},` : ''}
  contoursTilesBaseUrl: ${JSON.stringify(url && !url.includes('YOURPROJECT') ? `${url.replace(/\/$/, '')}/storage/v1/object/public/chart-tiles` : '')},
  contoursTilesVersion: 'v2',${webBundle ? `
  webBundle: ${JSON.stringify(webBundle)},` : ''}
};
`;

writeFileSync(outPath ? join(root, outPath) : join(root, 'bw-config.js'), out);
console.log('Generated ' + (outPath || 'bw-config.js'));
